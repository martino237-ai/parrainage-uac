require('dotenv').config();
const pool = require('./db');

async function ensureColumn(table, column, definition) {
  const isPg = !!(process.env.DB_DRIVER === 'postgres' || process.env.DATABASE_URL || process.env.SUPABASE_DB_URL);
  if (isPg) {
    const [rows] = await pool.query(
      `SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = $1 AND column_name = $2`,
      [table, column]
    );
    if (!rows.length) {
      await pool.query(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
    }
    return;
  }

  const [[found]] = await pool.query(
    'SELECT COUNT(*) AS n FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ? AND COLUMN_NAME = ?',
    [table, column]
  );
  if (!found.n) {
    await pool.query(`ALTER TABLE \`${table}\` ADD COLUMN \`${column}\` ${definition}`);
  }
}

async function ensureSchema() {
  const isPg = !!(process.env.DB_DRIVER === 'postgres' || process.env.DATABASE_URL || process.env.SUPABASE_DB_URL);

  if (isPg) {
    await ensureColumn('participants', 'motif_rejet', 'VARCHAR(500)');
    await ensureColumn('participants', 'updated_at', 'TIMESTAMPTZ NOT NULL DEFAULT NOW()');
    await pool.query(`CREATE TABLE IF NOT EXISTS audit_log (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      actor_id INT NULL,
      action VARCHAR(60) NOT NULL,
      entity_type VARCHAR(40) NOT NULL,
      entity_id INT NULL,
      reason VARCHAR(500) NULL,
      details JSONB NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES admins(id) ON DELETE SET NULL
    )`);
    await pool.query(`CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log (created_at)`);
    await pool.query(`CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_log (entity_type, entity_id)`);
    await pool.query(`CREATE INDEX IF NOT EXISTS idx_audit_actor ON audit_log (actor_id)`);
    return;
  }

  await ensureColumn('participants', 'motif_rejet', 'VARCHAR(500) NULL AFTER dossier');
  await ensureColumn('participants', 'updated_at', 'TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP AFTER created_at');
  await pool.query(`ALTER TABLE couples MODIFY COLUMN statut ENUM('propose','suspendu','valide') NOT NULL DEFAULT 'propose'`);
  await pool.query(`CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    actor_id INT NULL,
    action VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id INT NULL,
    reason VARCHAR(500) NULL,
    details JSON NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_audit_created (created_at),
    KEY idx_audit_entity (entity_type, entity_id),
    KEY idx_audit_actor (actor_id),
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES admins(id) ON DELETE SET NULL
  ) ENGINE=InnoDB`);
}

module.exports = { ensureSchema };

if (require.main === module) {
  ensureSchema()
    .then(() => console.log('Schéma vérifié et migrations appliquées.'))
    .catch(error => {
      console.error('Échec de la migration :', error.message);
      process.exitCode = 1;
    })
    .finally(() => pool.end());
}
